-- Уведомления о новых главах и компактные настройки по книжным полкам.
-- Существующая таблица notifications сохраняется и только расширяется.

create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  user_id bigint references public.users(user_id) on delete cascade,
  type text,
  title text,
  message text,
  link text,
  is_read boolean default false,
  created_at timestamptz default now()
);

alter table public.notifications
  add column if not exists novel_id bigint references public.novels(novel_id) on delete cascade,
  add column if not exists chapter_id bigint references public.chapters(chapter_id) on delete cascade,
  add column if not exists available_at timestamptz not null default now(),
  add column if not exists read_at timestamptz;

create table if not exists public.notification_preferences (
  user_id bigint primary key references public.users(user_id) on delete cascade,
  reading_enabled boolean not null default true,
  favorite_enabled boolean not null default true,
  want_to_read_enabled boolean not null default false,
  completed_enabled boolean not null default false,
  dropped_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists notifications_user_type_chapter_key
  on public.notifications (user_id, type, chapter_id);

create index if not exists notifications_user_available_idx
  on public.notifications (user_id, available_at desc);

create index if not exists notifications_user_unread_idx
  on public.notifications (user_id, is_read, available_at desc);

alter table public.notification_preferences enable row level security;
alter table public.notifications enable row level security;

comment on table public.notification_preferences is
  'Одна компактная строка личных настроек уведомлений на пользователя.';

comment on table public.notifications is
  'Уведомления пользователей; available_at поддерживает отложенные главы без постоянного таймера.';
