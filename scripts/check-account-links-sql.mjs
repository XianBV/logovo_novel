// Только изолированный PostgreSQL/WASM. Настоящая база не используется.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import crypto from 'node:crypto';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
let checks = 0;
const check = (value, text) => { assert.ok(value, text); checks++; };
const hash = 'a'.repeat(64), code = 'b'.repeat(64), nonce = 'c'.repeat(64);
const password = `pbkdf2-sha256$600000$${'d'.repeat(32)}$${'e'.repeat(64)}`;
for (const tokenType of ['text', 'uuid']) {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create table users(user_id bigint generated by default as identity primary key,telegram_id text unique,username text not null,
        role text not null,email text unique,password_hash text,email_verification_required boolean default false,email_verified_at timestamptz,
        is_banned boolean default false,created_at timestamptz default now(),last_active timestamptz,avatar_url text,bio text);
      create table sessions(id bigint generated by default as identity primary key,token ${tokenType},user_id bigint references users(user_id),created_at timestamptz,last_used timestamptz,expires_at timestamptz);
      create index on sessions(token);
      create table reading_lists(user_id bigint references users(user_id),novel_id bigint);
      insert into users(telegram_id,username,role,email,password_hash) values
        ('100','Telegram reader','reader',null,null),(null,'Email owner','owner','owner@example.test','old-password'),
        ('101','Another reader','reader',null,null),('102','Blocked','reader',null,null),('103','Wrong code','reader',null,null),('104','Quota reader','reader',null,null);
      update users set is_banned=true where user_id=4;
      insert into reading_lists values(1,99),(2,88);`);
    for (const name of ['202610290001_telegram_login.sql','202611050001_account_links.sql','202611050001_account_links.sql']) {
      await db.exec(await readFile(new URL('../supabase/migrations/' + name, import.meta.url), 'utf8'));
    }
    const sessions = new Map();
    for (let user = 1; user <= 6; user++) {
      const token = crypto.randomUUID(); sessions.set(user, token);
      await db.query("insert into sessions(token,user_id,created_at,expires_at) values($1,$2,now(),now()+interval '30 days')", [token,user]);
    }
    const call = async (name, args) => (await db.query(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')}) as r`,args)).rows[0].r;
    const begin = (user=1, email='reader@example.test', id=crypto.randomUUID(), session=sessions.get(user)) => call('auth_begin_email_link',[id,user,session,hash,email,password,code]).then(result=>({id,result,user}));
    const finish = (c, changes={}) => call('auth_finish_email_link',[c.id,changes.user??c.user,changes.session??sessions.get(c.user),changes.hash??hash,changes.code??code]);
    check((await begin(4)).result.code==='REAUTH_REQUIRED','Banned user rejected');
    check((await begin(1, 'x@example.test',crypto.randomUUID(),'wrong-session')).result.code==='REAUTH_REQUIRED','Wrong session rejected');
    check((await begin(1,'owner@example.test')).result.code==='IDENTITY_IN_USE','Existing email cannot move');
    check((await begin(1,'OWNER@example.test')).result===null,'Unnormalized email rejected');
    const c=await begin(); check(c.result.success,'Email challenge created');
    let user=(await db.query('select * from users where user_id=1')).rows[0];
    check(user.email===null&&user.password_hash===null,'Email/password unchanged until confirmation');
    check((await begin(1,'other@example.test')).result.code==='COOLDOWN','Cooldown cannot be bypassed with another address');
    check(await finish(c,{user:3,session:sessions.get(3)})===null,'Code bound to account');
    check((await finish(c,{session:sessions.get(3)}))?.code==='REAUTH_REQUIRED','Code bound to authenticated session');
    check(await finish(c,{hash:'f'.repeat(64)})===null,'Code bound to browser session hash');
    check(await finish(c,{code:'f'.repeat(64)})===null,'Wrong code rejected');
    check((await finish(c)).success,'Correct code attaches email');
    user=(await db.query('select * from users where user_id=1')).rows[0];
    check(user.email==='reader@example.test'&&user.email_verified_at&&user.password_hash===password,'Verified email and hash saved atomically');
    check(user.telegram_id==='100'&&user.role==='reader'&&user.username==='Telegram reader','Original identity and role preserved');
    check((await db.query('select novel_id from reading_lists where user_id=1')).rows[0].novel_id===99,'Shelves preserved');
    check(await finish(c)===null,'Email code cannot replay');
    check((await begin()).result===null,'Cannot replace an existing email');
    const wrong=await begin(5,'wrong@example.test');
    for(let i=0;i<5;i++) check(await finish(wrong,{code:'f'.repeat(64)})===null,'Wrong confirmation rejected');
    check(await finish(wrong)===null,'Five failed attempts invalidate code');
    const expired=await begin(3,'expired@example.test');
    await db.query("update account_email_links set expires_at=now()-interval '1 second' where challenge_id=$1",[expired.id]);
    check(await finish(expired)===null,'Expired code rejected');
    await db.query("update account_email_links set created_at=now()-interval '2 minutes' where user_id=3");
    const race=await begin(3,'race@example.test');
    await db.query("update users set email='race@example.test' where user_id=5");
    check((await finish(race)).code==='IDENTITY_IN_USE','Email claimed during confirmation is not stolen');
    check((await db.query('select email from users where user_id=3')).rows[0].email===null,'Conflict preserves account');
    for(let i=0;i<5;i++) {
      check((await begin(6,`quota-${i}@example.test`)).result.success,'Within hourly quota');
      await db.query("update account_email_links set created_at=now()-interval '2 minutes' where user_id=6");
    }
    check((await begin(6,'quota-next@example.test')).result.code==='COOLDOWN','Hourly quota enforced');
    const tgBegin=async()=>{const id=crypto.randomUUID(); check(await call('auth_begin_telegram_link',[id,'123',nonce,hash,2,sessions.get(2),hash]),'Telegram linking challenge issued');return id;};
    const tgFinish=(id,tg='900',overrides={})=>call('auth_finish_telegram_link',[id,'123',overrides.proof??hash,overrides.nonce??nonce,tg,overrides.user??2,overrides.session??sessions.get(2),overrides.hash??hash]);
    const t=await tgBegin();
    check(await call('auth_finish_telegram_login',[t,'123',hash,nonce,'900','Wrong',crypto.randomUUID()])===null,'Link challenge cannot be used as login');
    check(await tgFinish(t,'900',{user:3,session:sessions.get(3)})===null,'Telegram challenge bound to target account');
    check(await tgFinish(t,'900',{hash:'f'.repeat(64)})===null,'Telegram challenge bound to session hash');
    check(await tgFinish(t,'900',{nonce:'f'.repeat(64)})===null,'Telegram nonce checked');
    check((await tgFinish(t,'100')).code==='IDENTITY_IN_USE','Existing Telegram account cannot be taken');
    check((await db.query('select telegram_id from users where user_id=2')).rows[0].telegram_id===null,'Conflict does not modify target');
    const t2=await tgBegin(); const linked=await tgFinish(t2);
    check(linked.success&&linked.user.role==='owner'&&linked.user.username==='Email owner','Telegram attaches to existing owner without changing role or name');
    check(!JSON.stringify(linked).includes('old-password'),'Response omits password hash');
    check((await db.query('select password_hash,email from users where user_id=2')).rows[0].password_hash==='old-password','Email credentials preserved');
    check(await tgFinish(t2)===null,'Telegram challenge cannot replay');
    const normal=crypto.randomUUID(); await call('auth_begin_telegram_login',[normal,'123',nonce,hash]);
    const signedIn=await call('auth_finish_telegram_login',[normal,'123',hash,nonce,'900','Ignored',crypto.randomUUID()]);
    check(signedIn.user.user_id===2&&signedIn.user.role==='owner','Later Telegram login reuses linked account');
    check((await db.query('select count(*)::int as n from users')).rows[0].n===6,'No duplicate or merged accounts');
    await db.query("update sessions set created_at=now()-interval '16 minutes' where user_id=6");
    check((await begin(6)).result.code==='REAUTH_REQUIRED','Old session needs fresh sign-in');
    for(const role of ['anon','authenticated']) {
      await db.exec(`set role ${role}`);
      await assert.rejects(db.query('select * from account_email_links'),/permission denied/i); checks++;
      await assert.rejects(call('auth_link_user_json',[1]),/permission denied/i); checks++;
      await assert.rejects(begin(),/permission denied/i); checks++;
      await assert.rejects(tgFinish(t2),/permission denied/i); checks++;
      await db.exec('reset role');
    }
  } finally { await db.close(); }
}
console.log(`Account linking PostgreSQL: ${checks} checks passed; no real database used.`);
